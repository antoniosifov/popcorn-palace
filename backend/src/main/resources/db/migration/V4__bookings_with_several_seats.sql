-- A booking becomes an order that can contain several seats.
--
-- Before: one row in bookings = one seat.
-- After:  bookings is the order (who, which showtime, total);
--         booking_seats has one row per seat in it.
--
-- Existing single-seat bookings are kept: each becomes an order with one seat.

-- Lets booking_seats reference "this booking of this showtime" with one foreign key.
ALTER TABLE bookings
    ADD CONSTRAINT uq_bookings_id_showtime UNIQUE (id, showtime_id);

CREATE TABLE booking_seats
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id  UUID           NOT NULL,
    showtime_id BIGINT         NOT NULL,
    hall_id     BIGINT         NOT NULL,
    seat_id     BIGINT         NOT NULL,
    price       NUMERIC(10, 2) NOT NULL,
    -- The seat row carries the booking's showtime ...
    CONSTRAINT fk_booking_seats_booking FOREIGN KEY (booking_id, showtime_id)
        REFERENCES bookings (id, showtime_id) ON DELETE CASCADE,
    -- ... the showtime runs in this hall ...
    CONSTRAINT fk_booking_seats_showtime FOREIGN KEY (showtime_id, hall_id) REFERENCES showtimes (id, hall_id),
    -- ... and the seat is in that same hall.
    CONSTRAINT fk_booking_seats_seat FOREIGN KEY (seat_id, hall_id) REFERENCES seats (id, hall_id),
    -- One seat can be sold once per showtime. This is the guard against double
    -- booking: whatever happens in the application or in Redis, a second sale
    -- of the same seat cannot be stored.
    CONSTRAINT uq_booking_seats_showtime_seat UNIQUE (showtime_id, seat_id),
    CONSTRAINT ck_booking_seats_price CHECK (price >= 0)
);

CREATE INDEX idx_booking_seats_booking_id ON booking_seats (booking_id);

INSERT INTO booking_seats (booking_id, showtime_id, hall_id, seat_id, price)
SELECT id, showtime_id, hall_id, seat_id, price
FROM bookings;

ALTER TABLE bookings
    DROP CONSTRAINT uq_bookings_showtime_seat,
    DROP CONSTRAINT fk_bookings_seat,
    DROP CONSTRAINT ck_bookings_price,
    DROP COLUMN seat_id;

ALTER TABLE bookings
    RENAME COLUMN price TO total_price;

ALTER TABLE bookings
    ADD CONSTRAINT ck_bookings_total_price CHECK (total_price >= 0);
