-- Introduces halls with real seats, per-category prices, and moves the
-- "showtimes in one hall must not overlap" rule into the database.
--
-- Existing data is migrated, not dropped:
--   * every distinct showtimes.theater becomes a hall;
--   * each migrated hall gets 15 rows x 20 seats, because the previous API
--     accepted seat numbers 1..300 (seat n -> row (n-1)/20+1, seat (n-1)%20+1);
--   * showtimes.price becomes the STANDARD price of that showtime;
--   * each booking is pointed at its seat and keeps the price it was sold for.

-- Needed for an exclusion constraint that mixes "=" on a bigint with "&&" on a range.
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ---------------------------------------------------------------- halls, seats

CREATE TABLE halls
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    row_count  INTEGER      NOT NULL,
    seat_count INTEGER      NOT NULL,
    CONSTRAINT uq_halls_name UNIQUE (name),
    CONSTRAINT ck_halls_row_count CHECK (row_count > 0),
    CONSTRAINT ck_halls_seat_count CHECK (seat_count > 0)
);

CREATE TABLE seats
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hall_id     BIGINT      NOT NULL,
    row_number  INTEGER     NOT NULL,
    seat_number INTEGER     NOT NULL,
    category    VARCHAR(20) NOT NULL,
    CONSTRAINT fk_seats_hall FOREIGN KEY (hall_id) REFERENCES halls (id) ON DELETE CASCADE,
    CONSTRAINT uq_seats_position UNIQUE (hall_id, row_number, seat_number),
    -- Lets other tables reference "this seat in this hall" with one foreign key.
    CONSTRAINT uq_seats_id_hall UNIQUE (id, hall_id),
    CONSTRAINT ck_seats_row_number CHECK (row_number > 0),
    CONSTRAINT ck_seats_seat_number CHECK (seat_number > 0),
    CONSTRAINT ck_seats_category CHECK (category IN ('STANDARD', 'VIP'))
);

INSERT INTO halls (name, row_count, seat_count)
SELECT DISTINCT theater, 15, 300
FROM showtimes
ORDER BY theater;

INSERT INTO seats (hall_id, row_number, seat_number, category)
SELECT h.id, r, n, 'STANDARD'
FROM halls h
         CROSS JOIN generate_series(1, 15) AS r
         CROSS JOIN generate_series(1, 20) AS n;

-- ---------------------------------------------------------------- showtimes

ALTER TABLE showtimes
    ADD COLUMN hall_id BIGINT;

UPDATE showtimes s
SET hall_id = h.id
FROM halls h
WHERE h.name = s.theater;

ALTER TABLE showtimes
    ALTER COLUMN hall_id SET NOT NULL,
    ADD CONSTRAINT fk_showtimes_hall FOREIGN KEY (hall_id) REFERENCES halls (id),
    -- Lets bookings reference "this showtime in this hall" with one foreign key.
    ADD CONSTRAINT uq_showtimes_id_hall UNIQUE (id, hall_id);

CREATE TABLE showtime_prices
(
    showtime_id BIGINT         NOT NULL,
    category    VARCHAR(20)    NOT NULL,
    price       NUMERIC(10, 2) NOT NULL,
    CONSTRAINT pk_showtime_prices PRIMARY KEY (showtime_id, category),
    CONSTRAINT fk_showtime_prices_showtime FOREIGN KEY (showtime_id) REFERENCES showtimes (id) ON DELETE CASCADE,
    CONSTRAINT ck_showtime_prices_category CHECK (category IN ('STANDARD', 'VIP')),
    CONSTRAINT ck_showtime_prices_price CHECK (price >= 0)
);

INSERT INTO showtime_prices (showtime_id, category, price)
SELECT id, 'STANDARD', price
FROM showtimes;

DROP INDEX idx_showtimes_theater_start_time;

ALTER TABLE showtimes
    DROP COLUMN theater,
    DROP COLUMN price;

-- Two showtimes in the same hall may not overlap in time. The range is
-- half-open [start, end), so one may start exactly when the previous one ends.
-- Unlike a check in application code, this cannot be bypassed by two requests
-- arriving at the same moment.
ALTER TABLE showtimes
    ADD CONSTRAINT ex_showtimes_hall_time
        EXCLUDE USING gist (hall_id WITH =, tstzrange(start_time, end_time, '[)') WITH &&);

-- ---------------------------------------------------------------- bookings

ALTER TABLE bookings
    ADD COLUMN hall_id BIGINT,
    ADD COLUMN seat_id BIGINT,
    ADD COLUMN price   NUMERIC(10, 2);

UPDATE bookings b
SET hall_id = st.hall_id,
    seat_id = se.id,
    price   = sp.price
FROM showtimes st
         JOIN seats se ON se.hall_id = st.hall_id
         JOIN showtime_prices sp ON sp.showtime_id = st.id AND sp.category = se.category
WHERE st.id = b.showtime_id
  AND se.row_number = (b.seat_number - 1) / 20 + 1
  AND se.seat_number = (b.seat_number - 1) % 20 + 1;

ALTER TABLE bookings
    DROP CONSTRAINT uq_bookings_showtime_seat,
    DROP CONSTRAINT ck_bookings_seat_number,
    DROP CONSTRAINT fk_bookings_showtime,
    DROP COLUMN seat_number;

ALTER TABLE bookings
    ALTER COLUMN hall_id SET NOT NULL,
    ALTER COLUMN seat_id SET NOT NULL,
    ALTER COLUMN price SET NOT NULL,
    -- hall_id is repeated here on purpose: together these two composite foreign
    -- keys make it impossible to book a seat that is not in the showtime's hall,
    -- and to move a showtime with bookings to another hall.
    ADD CONSTRAINT fk_bookings_showtime FOREIGN KEY (showtime_id, hall_id) REFERENCES showtimes (id, hall_id),
    ADD CONSTRAINT fk_bookings_seat FOREIGN KEY (seat_id, hall_id) REFERENCES seats (id, hall_id),
    -- One seat can be sold once per showtime. This is the guard against double booking.
    ADD CONSTRAINT uq_bookings_showtime_seat UNIQUE (showtime_id, seat_id),
    ADD CONSTRAINT ck_bookings_price CHECK (price >= 0);
