-- Initial schema. Every business rule that must never be broken is enforced
-- here as a constraint, so it holds even when two requests race each other.
-- The API maps violations of the named constraints to error responses
-- (see ConstraintErrors in the application code).

CREATE TABLE movies
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(200)  NOT NULL,
    genre            VARCHAR(100)  NOT NULL,
    duration_minutes INTEGER       NOT NULL,
    rating           NUMERIC(3, 1) NOT NULL,
    release_year     INTEGER       NOT NULL,
    CONSTRAINT uq_movies_title UNIQUE (title),
    CONSTRAINT ck_movies_duration CHECK (duration_minutes > 0),
    CONSTRAINT ck_movies_rating CHECK (rating BETWEEN 0 AND 10),
    CONSTRAINT ck_movies_release_year CHECK (release_year BETWEEN 1888 AND 2100)
);

CREATE TABLE showtimes
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id   BIGINT         NOT NULL,
    theater    VARCHAR(100)   NOT NULL,
    start_time TIMESTAMPTZ    NOT NULL,
    end_time   TIMESTAMPTZ    NOT NULL,
    price      NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_showtimes_movie FOREIGN KEY (movie_id) REFERENCES movies (id),
    CONSTRAINT ck_showtimes_time_range CHECK (end_time > start_time),
    CONSTRAINT ck_showtimes_price CHECK (price >= 0)
);

CREATE INDEX idx_showtimes_movie_id ON showtimes (movie_id);
-- Supports the overlap check: showtimes of one theater ordered by time.
CREATE INDEX idx_showtimes_theater_start_time ON showtimes (theater, start_time);

CREATE TABLE bookings
(
    id          UUID PRIMARY KEY,
    showtime_id BIGINT      NOT NULL,
    seat_number INTEGER     NOT NULL,
    user_id     UUID        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_bookings_showtime FOREIGN KEY (showtime_id) REFERENCES showtimes (id),
    CONSTRAINT ck_bookings_seat_number CHECK (seat_number BETWEEN 1 AND 300),
    -- One seat can be sold once per showtime. This is the guard against double booking.
    CONSTRAINT uq_bookings_showtime_seat UNIQUE (showtime_id, seat_number)
);

CREATE INDEX idx_bookings_user_id ON bookings (user_id);
